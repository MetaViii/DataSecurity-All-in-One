export const parameterLabel = (name) => parameterNames[name] || name;
export const choiceLabel = (name, value) => choices[name]?.[String(value)] || String(value);

// Draft hints only; Pipeline.plan remains the authoritative check.
export function draftProblems(nodes, edges) {
  const problems = [];
  for (const node of nodes) {
    if (node.data.unknown) problems.push({ node: node.id, message: '插件尚未加载' });
    for (const port of node.data.plugin.inputs) {
      if (!edges.some((edge) => edge.target === node.id && edge.targetHandle === port))
        problems.push({ node: node.id, message: `缺少输入连接：${port}` });
    }
    for (const parameter of node.data.plugin.parameters) {
      const value = node.data.config[parameter.name] ?? parameter.default;
      if (
        parameter.required &&
        (value === undefined ||
          value === '' ||
          (Array.isArray(value) && !value.length) ||
          (value &&
            typeof value === 'object' &&
            !Array.isArray(value) &&
            !Object.keys(value).length))
      )
        problems.push({ node: node.id, message: `请填写${parameterLabel(parameter.name)}` });
    }
  }
  return problems;
}
